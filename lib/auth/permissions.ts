/**
 * Safely maps any role string to normalized BuildStockRole
 */
export function normalizeRole(role?: string | null): string {
  if (!role) return BuildStockRoles.VIEWER;
  
  const normalized = role.trim();
  if (normalized === "admin" || normalized === "SUPER_ADMIN") return BuildStockRoles.SUPER_ADMIN;
  if (normalized === "WAREHOUSE_MANAGER") return BuildStockRoles.WAREHOUSE_MANAGER;
  if (normalized === "STOREKEEPER") return BuildStockRoles.STOREKEEPER;
  if (normalized === "PURCHASING_OFFICER" || normalized === "supplier") return BuildStockRoles.PURCHASING_OFFICER;
  if (normalized === "INVENTORY_OFFICER") return BuildStockRoles.INVENTORY_OFFICER;
  return BuildStockRoles.VIEWER;
}

/**
 * Checks if a given role possesses a specific permission
 */
export function hasPermission(role?: string | null, permission?: PermissionName): boolean {
  if (!permission) return true;
  const userRole = role || BuildStockRoles.VIEWER;
  
  // Super admin has all permissions
  if (userRole === BuildStockRoles.SUPER_ADMIN || userRole === "admin") {
    return true;
  }

  const permissions = ROLE_PERMISSIONS[userRole] || ROLE_PERMISSIONS[BuildStockRoles.VIEWER] || [];
  return permissions.includes(permission);
}
